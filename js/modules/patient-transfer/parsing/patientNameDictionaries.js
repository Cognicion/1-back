function normalizeEntry(value = "") {
  return String(value || "").normalize("NFD").replace(/[\u0300-\u036f]/g, "").replace(/\s+/g, " ").trim().toLowerCase();
}

function readLearnedDictionary() {
  if (typeof localStorage === "undefined") return { givenNames: [], surnames: [] };
  try {
    const stored = JSON.parse(localStorage.getItem(STORAGE_KEY) || "{}");
    return {
      givenNames: Array.isArray(stored.givenNames) ? stored.givenNames : [],
      surnames: Array.isArray(stored.surnames) ? stored.surnames : []
    };
  } catch { return { givenNames: [], surnames: [] }; }
}

function writeLearnedDictionary(dictionary) {
  if (typeof localStorage !== "undefined") localStorage.setItem(STORAGE_KEY, JSON.stringify(dictionary));
}

export function getGivenNamesDictionary() {
  return new Set([...COMMON_GIVEN_NAMES, ...readLearnedDictionary().givenNames].map(normalizeEntry).filter(Boolean));
}

export function getSurnamesDictionary() {
  return new Set([...COMMON_SURNAMES, ...readLearnedDictionary().surnames].map(normalizeEntry).filter(Boolean));
}

export function registerPatientNameParts({ nombres = "", apellidoPaterno = "", apellidoMaterno = "" } = {}) {
  const dictionary = readLearnedDictionary();
  const givenNames = new Set(dictionary.givenNames.map(normalizeEntry).filter(Boolean));
  const surnames = new Set(dictionary.surnames.map(normalizeEntry).filter(Boolean));
  String(nombres).split(/\s+/).map(normalizeEntry).filter(Boolean).forEach((value) => givenNames.add(value));
  [apellidoPaterno, apellidoMaterno].map(normalizeEntry).filter(Boolean).forEach((value) => surnames.add(value));
  const next = { givenNames: [...givenNames].sort(), surnames: [...surnames].sort() };
  writeLearnedDictionary(next);
  return next;
}
